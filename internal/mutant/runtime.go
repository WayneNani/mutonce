package mutant

import (
	"bytes"
	"fmt"
)

// The runtime helpers are appended to the first mutated file of every
// package rather than added as a file of their own: the go command ignores
// new overlay files in module cache directories, and unexported helpers per
// package need no shared runtime package.

// runtimeImports are added to the host file under these names.
var runtimeImports = [][2]string{
	{"_moerrors", "errors"},
	{"_moos", "os"},
	{"_mostrconv", "strconv"},
	{"_mosync", "sync"},
}

const schemaActiveDecl = `var _moActive, _ = _mostrconv.Atoi(_moos.Getenv("MUTONCE_ACTIVE"))`

// WithActive hard-codes one mutant in a host file instead of reading
// MUTONCE_ACTIVE, so the compiler drops all other variants. The naive
// comparison mode builds one binary per mutant this way.
func WithActive(host []byte, id int) []byte {
	return bytes.Replace(host, []byte(schemaActiveDecl), fmt.Appendf(nil, "const _moActive = %d", id), 1)
}

// The variables are initialised before any package-level variable that runs
// mutated code, because Go orders initialisation by references, including
// references through function bodies.
const runtimeBody = `
// Code below generated by mutonce.

` + schemaActiveDecl + `

var (
	_moRecPath = _moos.Getenv("MUTONCE_RECORD")
	_moErr     = _moerrors.New("mutonce: injected error")
	_moMu      _mosync.Mutex
	_moSeen    = map[int]bool{}
)

// _moRecord appends every mutation point reached for the first time to the
// file named by MUTONCE_RECORD.
func _moRecord(lo, hi int) {
	_moMu.Lock()
	defer _moMu.Unlock()
	var buf []byte
	for id := lo; id < hi; id++ {
		if !_moSeen[id] {
			_moSeen[id] = true
			buf = _mostrconv.AppendInt(buf, int64(id), 10)
			buf = append(buf, '\n')
		}
	}
	if len(buf) == 0 {
		return
	}
	f, err := _moos.OpenFile(_moRecPath, _moos.O_APPEND|_moos.O_CREATE|_moos.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	f.Write(buf)
	f.Close()
}

func _moIs(id int) bool {
	if _moRecPath != "" {
		_moRecord(id, id+1)
	}
	return _moActive == id
}

func _moNoErr(id int, err error) error {
	if _moIs(id) {
		return nil
	}
	return err
}

func _moOff(base, n int) bool {
	if _moRecPath != "" {
		_moRecord(base, base+n)
	}
	return _moActive < base || _moActive >= base+n
}

// _moC notes the value of condition k in the vector of its decision: bit k
// marks it as evaluated, bit 32+k holds its value.
func _moC(v *uint64, k uint, c bool) bool {
	*v |= 1 << k
	if c {
		*v |= 1 << (32 + k)
	}
	return c
}

// _moD records the vector and outcome of decision d for MC/DC.
func _moD(d int, r bool, v *uint64) bool {
	if _moRecPath != "" {
		_moRecordVec(d, *v, r)
	}
	return r
}

type _moVec struct {
	d int
	v uint64
	r bool
}

var _moVecs = map[_moVec]bool{}

// _moRecordVec appends every vector seen for the first time to the file
// named by MUTONCE_RECORD as "d <decision> <vector> <outcome>".
func _moRecordVec(d int, v uint64, r bool) {
	_moMu.Lock()
	defer _moMu.Unlock()
	key := _moVec{d, v, r}
	if _moVecs[key] {
		return
	}
	_moVecs[key] = true
	buf := []byte("d ")
	buf = _mostrconv.AppendInt(buf, int64(d), 10)
	buf = append(buf, ' ')
	buf = _mostrconv.AppendUint(buf, v, 10)
	buf = append(buf, ' ')
	buf = _mostrconv.AppendBool(buf, r)
	buf = append(buf, '\n')
	f, err := _moos.OpenFile(_moRecPath, _moos.O_APPEND|_moos.O_CREATE|_moos.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	f.Write(buf)
	f.Close()
}
`
